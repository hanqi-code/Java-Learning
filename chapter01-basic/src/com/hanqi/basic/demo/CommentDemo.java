package com.hanqi.basic.demo;

/**
 * 文档注释：可以为类添加说明。
 */
public class CommentDemo {
    public static void main(String[] args) {
        // 单行注释：说明代码，不会被执行。
        System.out.println("学习单行注释");

        /*
         * 多行注释可以写多行说明。
         * 注释中的文字不会显示在控制台。
         */
        System.out.println("学习多行注释");
        // 练习：注释掉上一行，再运行，观察输出的变化。
    }
}

