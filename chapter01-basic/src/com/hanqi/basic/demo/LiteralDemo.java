package com.hanqi.basic.demo;

/**
 * Chapter01 基础练习：LiteralDemo。
 */
public class LiteralDemo {
    public static void main(String[] args) {
        System.out.println(100);          // 整数字面量
        System.out.println(3.14);         // 小数字面量
        System.out.println('中');         // 字符：单引号，只表示一个字符
        System.out.println("学习 Java");  // 字符串：双引号
        System.out.println(true);        // 布尔值
        System.out.println(false);
        System.out.println("第一行\n第二行"); // \n 表示换行
        System.out.println("姓名\t年龄");     // \t 表示制表符
        // 练习：分别输出自己的年龄、一个汉字和一句话。
    }
}

