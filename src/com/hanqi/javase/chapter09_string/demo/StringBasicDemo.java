package com.hanqi.javase.chapter09_string.demo;

public class StringBasicDemo {
    public static void main(String[] args) {
        String name = "涵琦";
        String book = "Java";
        System.out.println("姓名：" + name);
        System.out.println("姓名长度：" + name.length());
        System.out.println();
        System.out.println("书名：" + book);
        System.out.println("书名长度：" + book.length());
    }
}
