package com.hanqi.javase.chapter09_string.lab;

public class StringCharAtPractice {
    public static void main(String[] args) {
        String game = "Minecraft";
        System.out.println(game.charAt(0));
        System.out.println(game.charAt(3));
        System.out.println(game.charAt(game.length()-1));
    }
}
