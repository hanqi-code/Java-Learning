package com.hanqi.javase.chapter09_string.lab;

public class StringBasicPractice {
    public static void main(String[] args) {
        String movie = "Interstellar";
        String game = "Stardew Valley";
        System.out.println("电影：" + movie);
        System.out.println("电影长度：" + movie.length());
        System.out.println();
        System.out.println("游戏：" + game);
        System.out.println("游戏长度：" + game.length());
    }
}
